// Runs every tests/*.test.ts through the node:test run() API, writes docs/test-results.md and fills the
// Actual / Pass-Fail columns of docs/test-cases.md from the run.  Usage: npm run test:report
import fs from "node:fs";
import path from "node:path";
import { run } from "node:test";

interface Result { id: string; title: string; ok: boolean; ms: number; error: string }

const root = process.cwd();
const files = fs.readdirSync(path.join(root, "tests")).filter((f) => f.endsWith(".test.ts")).sort().map((f) => path.join(root, "tests", f));
const results: Result[] = [];
const idOf = (name: string) => /^([A-Z]+-\d+)\b/.exec(name)?.[1];

async function main() {
  // isolation "none": test files are imported into this (tsx) process, so TypeScript just works.
  for await (const ev of run({ files, isolation: "none" } as Parameters<typeof run>[0]) /* isolation: Node 22.8+, newer than @types/node 20 */) {
    if (ev.type !== "test:pass" && ev.type !== "test:fail") continue;
    const d = ev.data as { name: string; details: { duration_ms: number; type?: string; error?: Error & { cause?: Error } } };
    const id = idOf(d.name);
    if (!id || d.details.type === "suite") continue;
    const err = d.details.error;
    results.push({ id, title: d.name, ok: ev.type === "test:pass", ms: d.details.duration_ms, error: err ? (err.cause?.message ?? err.message).split("\n")[0] : "" });
}

  const stamp = new Date().toISOString().replace("T", " ").slice(0, 19);
  const passed = results.filter((r) => r.ok).length;
  const failed = results.length - passed;
  const cell = (s: string) => s.replace(/\|/g, "\\|");

  fs.writeFileSync(path.join(root, "docs", "test-results.md"), [
    "# Test results", "",
    `Generated by \`npm run test:report\` on ${stamp} (UTC). Files: ${files.map((f) => path.relative(root, f)).join(", ")}.`, "",
    `**${passed} passed, ${failed} failed** (${results.length} tests).`, "",
    "| ID | Title | Result | Duration (ms) | Timestamp |", "|----|-------|--------|---------------|-----------|",
    ...results.map((r) => `| ${r.id} | ${cell(r.title.replace(/^[A-Z]+-\d+\s*/, ""))} | ${r.ok ? "PASS" : `FAIL: ${cell(r.error)}`} | ${r.ms.toFixed(1)} | ${stamp} |`),
    "",
  ].join("\n"));

  // Fill Actual / Pass-Fail in the test-case tables (rows: | ID | Module | Description | Input | Expected | Actual | Pass/Fail |)
  const casesFile = path.join(root, "docs", "test-cases.md");
  const byId = new Map(results.map((r) => [r.id, r]));
  const missing = new Set(byId.keys());
  const lines = fs.readFileSync(casesFile, "utf8").split("\n").map((line) => {
    if (/^Last run/.test(line)) return `Last run (whole suite, ${stamp} UTC): ${passed} passed, ${failed} failed. Details: [test-results.md](test-results.md).`;
    const cols = line.split(/(?<!\\)\|/);
    if (cols.length !== 9) return line;
    const r = byId.get(cols[1].trim());
    if (!r) return line;
    missing.delete(r.id);
    cols[6] = ` ${r.ok ? (cols[6].trim() && !cols[6].includes("FAILED") ? cols[6].trim() : "As expected") : `FAILED: ${cell(r.error)}`} `;
    cols[7] = ` ${r.ok ? "Pass" : "Fail"} `;
    return cols.join("|");
  });
  fs.writeFileSync(casesFile, lines.join("\n"));

  console.log(`${passed} passed, ${failed} failed -> docs/test-results.md, docs/test-cases.md updated`);
  if (missing.size) console.log(`Not documented in test-cases.md: ${[...missing].join(", ")}`);
  process.exitCode = failed || missing.size ? 1 : 0;
}

void main();
